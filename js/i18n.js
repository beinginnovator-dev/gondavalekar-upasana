function t(key) {
  const lang = localStorage.getItem('lang') || 'en';
  return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
}

function applyTranslations() {
  const lang = localStorage.getItem('lang') || 'en';
  document.body.classList.remove('lang-en', 'lang-hi', 'lang-mr');
  document.body.classList.add('lang-' + lang);
  document.documentElement.lang = lang === 'mr' ? 'mr' : lang === 'hi' ? 'hi' : 'en';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val) el.textContent = val;
  });

  // Re-render dynamic sections
  if (typeof renderSchedule === 'function') renderSchedule();
  if (typeof renderTeachings === 'function') renderTeachings();
  if (typeof renderReminderOptions === 'function') renderReminderOptions();
  if (typeof renderCalendarButtons === 'function') renderCalendarButtons();
}
